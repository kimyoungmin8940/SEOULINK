const fallbackStayMinutesByCategory = Object.freeze({
    TOUR: 75,
    RESTAURANT: 60,
    CAFE: 50,
    HOTEL: 720,
});

export function getThemePlaceStayMinutes(placeName, category) {
    const placeMinutes = stayMinutesByPlaceName[placeName];

    if (Number.isFinite(placeMinutes) && placeMinutes > 0) {
        return placeMinutes;
    }

    return fallbackStayMinutesByCategory[category] || 60;
}

export { fallbackStayMinutesByCategory, stayMinutesByPlaceName };
