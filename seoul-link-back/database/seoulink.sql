                                MEMBER_ID NUMBER NOT NULL,

                                RESULT_ID NUMBER,
                                PAYMENT_ID NUMBER,

                                TITLE VARCHAR2(200) NOT NULL,
                                DESCRIPTION CLOB,

                                TRAVEL_CODE CHAR(5),

                                COURSE_TYPE VARCHAR2(20) DEFAULT 'CUSTOM' NOT NULL,

                                REGION VARCHAR2(100),

                                IS_PUBLIC CHAR(1) DEFAULT 'N' NOT NULL,

                                VIEW_COUNT NUMBER DEFAULT 0 NOT NULL,

                                TOTAL_DISTANCE_KM NUMBER(12, 3) DEFAULT 0 NOT NULL,
                                TOTAL_TRAVEL_MINUTES NUMBER(12, 2) DEFAULT 0 NOT NULL,
                                TOTAL_VISIT_MINUTES NUMBER DEFAULT 0 NOT NULL,
                                TOTAL_COURSE_MINUTES NUMBER(12, 2) DEFAULT 0 NOT NULL,

                                CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
                                UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,

                                CONSTRAINT FK_COURSE_MEMBER
                                    FOREIGN KEY (MEMBER_ID)
                                        REFERENCES MEMBER(MEMBER_ID)
                                        ON DELETE CASCADE,

                                CONSTRAINT FK_COURSE_RESULT
                                    FOREIGN KEY (RESULT_ID)
                                        REFERENCES SURVEY_RESULT(RESULT_ID),

                                CONSTRAINT FK_COURSE_PAYMENT
                                    FOREIGN KEY (PAYMENT_ID)
                                        REFERENCES PAYMENT(PAYMENT_ID),

                                CONSTRAINT FK_COURSE_TYPE
                                    FOREIGN KEY (TRAVEL_CODE)
                                        REFERENCES TRAVEL_TYPE_MASTER(TRAVEL_CODE),

                                CONSTRAINT CK_COURSE_TYPE
                                    CHECK (COURSE_TYPE IN ('CUSTOM', 'SURVEY', 'CHATBOT')),

                                CONSTRAINT CK_COURSE_PUBLIC
                                    CHECK (IS_PUBLIC IN ('Y', 'N')),

                                CONSTRAINT CK_COURSE_VIEW_COUNT
                                    CHECK (VIEW_COUNT >= 0),

                                CONSTRAINT CK_COURSE_TOTAL_DISTANCE
                                    CHECK (TOTAL_DISTANCE_KM >= 0),

                                CONSTRAINT CK_COURSE_TOTAL_TRAVEL
                                    CHECK (TOTAL_TRAVEL_MINUTES >= 0),

                                CONSTRAINT CK_COURSE_TOTAL_VISIT
                                    CHECK (TOTAL_VISIT_MINUTES >= 0),

                                CONSTRAINT CK_COURSE_TOTAL_TIME
                                    CHECK (TOTAL_COURSE_MINUTES >= 0)
);

-- COURSE_DETAILS
CREATE TABLE COURSE_DETAILS (
                                DETAIL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                    CONSTRAINT PK_COURSE_DETAILS PRIMARY KEY,

                                COURSE_ID NUMBER NOT NULL,
                                PLACE_ID NUMBER NOT NULL,

                                DAY_NO NUMBER DEFAULT 1 NOT NULL,
                                PLACE_ORDER NUMBER NOT NULL,

                                MEMO VARCHAR2(500),
                                VISIT_TIME VARCHAR2(50),
                                STAY_MINUTES NUMBER,

                                VISIT_DATE DATE,
                                DISTANCE_FROM_PREV_KM NUMBER(12, 3) DEFAULT 0 NOT NULL,
                                TRAVEL_MINUTES_FROM_PREV NUMBER(12, 2) DEFAULT 0 NOT NULL,

                                CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

                                CONSTRAINT FK_DETAILS_COURSE
                                    FOREIGN KEY (COURSE_ID)
                                        REFERENCES TRAVEL_COURSES(COURSE_ID)
                                        ON DELETE CASCADE,

                                CONSTRAINT FK_DETAILS_PLACE
                                    FOREIGN KEY (PLACE_ID)
                                        REFERENCES PLACES(PLACE_ID),

                                CONSTRAINT UK_COURSE_ORDER
                                    UNIQUE (COURSE_ID, DAY_NO, PLACE_ORDER),

                                CONSTRAINT CK_COURSE_DAY
                                    CHECK (DAY_NO >= 1),

                                CONSTRAINT CK_COURSE_ORDER
                                    CHECK (PLACE_ORDER >= 1),

                                CONSTRAINT CK_COURSE_STAY
                                    CHECK (STAY_MINUTES IS NULL OR STAY_MINUTES >= 0),

                                CONSTRAINT CK_DETAIL_PREV_DISTANCE
                                    CHECK (DISTANCE_FROM_PREV_KM >= 0),

                                CONSTRAINT CK_DETAIL_PREV_TRAVEL
                                    CHECK (TRAVEL_MINUTES_FROM_PREV >= 0)
