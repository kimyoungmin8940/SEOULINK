-- 테이블이 아직 없어도 중단되지 않도록 자식 테이블부터 안전하게 삭제
DECLARE
TYPE TABLE_NAME_LIST IS TABLE OF VARCHAR2(30);
    TABLE_NAMES TABLE_NAME_LIST := TABLE_NAME_LIST(
        'REVIEW_COMMENT',
        'REVIEW_LIKE',
        'REVIEW',
        'CHATBOT_HISTORY',
        'COURSE_DETAILS',
        'TRAVEL_COURSES',
        'SURVEY_RESULT',
        'TRAVEL_TYPE_PLACE',
        'SURVEY_ANSWER',
        'TRAVEL_SURVEY',
        'PAYMENT',
        'PLACES',
        'SURVEY_OPTION',
        'SURVEY_QUESTION',
        'TRAVEL_TYPE_MASTER',
        'MEMBER'
    );
BEGIN
FOR I IN 1 .. TABLE_NAMES.COUNT LOOP
BEGIN
EXECUTE IMMEDIATE
    'DROP TABLE ' || TABLE_NAMES(I) || ' CASCADE CONSTRAINTS';
EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN
                    RAISE;
END IF;
END;
END LOOP;
END;

-- MEMBER
CREATE TABLE MEMBER (
                        MEMBER_ID NUMBER GENERATED ALWAYS AS IDENTITY
                            CONSTRAINT PK_MEMBER PRIMARY KEY,

                        EMAIL VARCHAR2(100) NOT NULL,
                        PASSWORD VARCHAR2(255) NOT NULL,
                        NAME VARCHAR2(50) NOT NULL,
                        NICKNAME VARCHAR2(50),
                        PHONE VARCHAR2(20),

                        LOGIN_TYPE VARCHAR2(20) DEFAULT 'LOCAL' NOT NULL,

                        STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

                        CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
                        UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,

                        CONSTRAINT UK_MEMBER_EMAIL UNIQUE (EMAIL),
                        CONSTRAINT UK_MEMBER_NICKNAME UNIQUE (NICKNAME),

                        CONSTRAINT CK_MEMBER_STATUS
                            CHECK (STATUS IN ('ACTIVE', 'WITHDRAWN'))
);

-- TRAVEL_TYPE_MASTER
CREATE TABLE TRAVEL_TYPE_MASTER (
                                    TRAVEL_CODE CHAR(5)
                                        CONSTRAINT PK_TRAVEL_TYPE PRIMARY KEY,

                                    TYPE_TITLE VARCHAR2(100) NOT NULL,
                                    TYPE_DESCRIPTION VARCHAR2(2000) NOT NULL,
                                    IMAGE_URL VARCHAR2(500)
);

-- SURVEY_QUESTION
CREATE TABLE SURVEY_QUESTION (
                                 QUESTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                     CONSTRAINT PK_SURVEY_QUESTION PRIMARY KEY,

                                 QUESTION_TEXT VARCHAR2(500) NOT NULL,
                                 CATEGORY VARCHAR2(30) NOT NULL
);

-- SURVEY_OPTION
CREATE TABLE SURVEY_OPTION (
                               OPTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                   CONSTRAINT PK_SURVEY_OPTION PRIMARY KEY,

                               QUESTION_ID NUMBER NOT NULL,
                               OPTION_TEXT VARCHAR2(300) NOT NULL,
                               SCORE_CODE VARCHAR2(20) NOT NULL,
                               SCORE_VALUE NUMBER DEFAULT 1 NOT NULL,

                               CONSTRAINT FK_OPTION_QUESTION
                                   FOREIGN KEY (QUESTION_ID)
                                       REFERENCES SURVEY_QUESTION(QUESTION_ID)
                                       ON DELETE CASCADE,

                               CONSTRAINT UK_OPTION_QUESTION
                                   UNIQUE (QUESTION_ID, OPTION_ID)
);

-- PLACES
