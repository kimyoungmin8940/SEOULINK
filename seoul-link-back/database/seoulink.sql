-- PAYMENT
CREATE TABLE PAYMENT (
                         PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                             CONSTRAINT PK_PAYMENT PRIMARY KEY,

                         MEMBER_ID NUMBER NOT NULL,

                         PRODUCT_NAME VARCHAR2(100) NOT NULL,
                         AMOUNT NUMBER DEFAULT 0 NOT NULL,

                         PAYMENT_METHOD VARCHAR2(30) NOT NULL,
                         PAYMENT_PROVIDER VARCHAR2(30),

                         ORDER_ID VARCHAR2(100) NOT NULL,
                         PAYMENT_KEY VARCHAR2(200),

                         PAYMENT_STATUS VARCHAR2(20) DEFAULT 'READY' NOT NULL,

                         REMAIN_COUNT NUMBER DEFAULT 0 NOT NULL,
                         EXPIRED_AT DATE,

                         PAID_AT DATE,
                         CANCELED_AT DATE,
                         FAIL_REASON VARCHAR2(500),

                         CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

                         CONSTRAINT FK_PAYMENT_MEMBER
                             FOREIGN KEY (MEMBER_ID)
                                 REFERENCES MEMBER(MEMBER_ID),

                         CONSTRAINT UK_PAYMENT_ORDER
                             UNIQUE (ORDER_ID),

                         CONSTRAINT CK_PAYMENT_AMOUNT
                             CHECK (AMOUNT >= 0),

                         CONSTRAINT CK_PAYMENT_REMAIN
                             CHECK (REMAIN_COUNT >= 0),

                         CONSTRAINT CK_PAYMENT_STATUS
                             CHECK (PAYMENT_STATUS IN ('READY', 'PAID', 'CANCELED', 'FAILED'))
);

-- TRAVEL_SURVEY
CREATE TABLE TRAVEL_SURVEY (
                               SURVEY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                   CONSTRAINT PK_TRAVEL_SURVEY PRIMARY KEY,

                               MEMBER_ID NUMBER,
                               GUEST_TOKEN VARCHAR2(100),

                               REGION VARCHAR2(50) NOT NULL,
                               START_DATE DATE NOT NULL,
                               END_DATE DATE NOT NULL,
                               PEOPLE_COUNT NUMBER NOT NULL,

                               CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

                               CONSTRAINT FK_SURVEY_MEMBER
                                   FOREIGN KEY (MEMBER_ID)
                                       REFERENCES MEMBER(MEMBER_ID)
                                       ON DELETE CASCADE,

                               CONSTRAINT UK_SURVEY_GUEST_TOKEN
                                   UNIQUE (GUEST_TOKEN),

                               CONSTRAINT CK_SURVEY_OWNER
                                   CHECK (MEMBER_ID IS NOT NULL OR GUEST_TOKEN IS NOT NULL),

                               CONSTRAINT CK_SURVEY_DATE
                                   CHECK (END_DATE >= START_DATE),

                               CONSTRAINT CK_SURVEY_PEOPLE
                                   CHECK (PEOPLE_COUNT >= 1)
);

-- SURVEY_ANSWER
CREATE TABLE SURVEY_ANSWER (
                               ANSWER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                   CONSTRAINT PK_SURVEY_ANSWER PRIMARY KEY,

                               SURVEY_ID NUMBER NOT NULL,
                               QUESTION_ID NUMBER NOT NULL,
                               OPTION_ID NUMBER NOT NULL,

                               CONSTRAINT FK_ANSWER_SURVEY
                                   FOREIGN KEY (SURVEY_ID)
                                       REFERENCES TRAVEL_SURVEY(SURVEY_ID)
                                       ON DELETE CASCADE,

                               CONSTRAINT FK_ANSWER_QUESTION
                                   FOREIGN KEY (QUESTION_ID)
                                       REFERENCES SURVEY_QUESTION(QUESTION_ID),

                               CONSTRAINT FK_ANSWER_OPTION
                                   FOREIGN KEY (QUESTION_ID, OPTION_ID)
                                       REFERENCES SURVEY_OPTION(QUESTION_ID, OPTION_ID),

                               CONSTRAINT UK_ANSWER_SURVEY_QUESTION
                                   UNIQUE (SURVEY_ID, QUESTION_ID)
);

-- TRAVEL_TYPE_PLACE
CREATE TABLE TRAVEL_TYPE_PLACE (
                                   TYPE_PLACE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                       CONSTRAINT PK_TRAVEL_TYPE_PLACE PRIMARY KEY,

                                   TRAVEL_CODE CHAR(5) NOT NULL,
                                   PLACE_ID NUMBER NOT NULL,

                                   WEIGHT_SCORE NUMBER DEFAULT 1 NOT NULL,

