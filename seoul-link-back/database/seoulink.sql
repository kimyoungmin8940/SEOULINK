-- SURVEY_RESULT
CREATE TABLE SURVEY_RESULT (
                               RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
                                   CONSTRAINT PK_SURVEY_RESULT PRIMARY KEY,

                               SURVEY_ID NUMBER NOT NULL,
                               TRAVEL_CODE CHAR(5) NOT NULL,

