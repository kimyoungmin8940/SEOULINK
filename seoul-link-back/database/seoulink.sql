                        CONSTRAINT CK_PLACES_HISTORY CHECK (TAG_HISTORY IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_MODERN CHECK (TAG_MODERN IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_BUDGET CHECK (TAG_BUDGET IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_LUXURY CHECK (TAG_LUXURY IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_STABLE CHECK (TAG_STABLE IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_DOPAMINE CHECK (TAG_DOPAMINE IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_RELAX CHECK (TAG_RELAX IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_PACKED CHECK (TAG_PACKED IN ('Y', 'N')),
                        CONSTRAINT CK_PLACES_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
