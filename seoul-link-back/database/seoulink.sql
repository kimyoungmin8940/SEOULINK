                            CONSTRAINT PK_PLACES PRIMARY KEY,

                        API_PROVIDER VARCHAR2(30) NOT NULL,
                        API_PLACE_ID VARCHAR2(100) NOT NULL,
                        CONTENT_ID NUMBER,

                        NAME VARCHAR2(200) NOT NULL,
                        CATEGORY VARCHAR2(50) NOT NULL,
                        API_CATEGORY VARCHAR2(200),

                        REGION VARCHAR2(100) NOT NULL,
                        ADDRESS VARCHAR2(500) NOT NULL,
                        ROAD_ADDRESS VARCHAR2(500),

                        LATITUDE NUMBER(10, 7) NOT NULL,
                        LONGITUDE NUMBER(10, 7) NOT NULL,

                        PHONE VARCHAR2(50),
                        PLACE_URL VARCHAR2(1000),

                        RATING NUMBER(3, 2) DEFAULT 0.0 NOT NULL,
                        REVIEW_COUNT NUMBER DEFAULT 0 NOT NULL,

                        DESCRIPTION CLOB,
                        IMAGE_URL VARCHAR2(1000),

                        TAG_HISTORY CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_MODERN CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_BUDGET CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_LUXURY CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_STABLE CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_DOPAMINE CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_RELAX CHAR(1) DEFAULT 'N' NOT NULL,
                        TAG_PACKED CHAR(1) DEFAULT 'N' NOT NULL,

                        IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,

                        CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
                        UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,

