-- 설문 관련 테이블
-- seoul-link-back(52)의 JPA 엔티티를 기준으로 작성

CREATE TABLE TRAVEL_TYPE_MASTER (
    TRAVEL_CODE CHAR(5)
        CONSTRAINT PK_TRAVEL_TYPE PRIMARY KEY,

    TYPE_TITLE VARCHAR2(100) NOT NULL,
    TYPE_DESCRIPTION VARCHAR2(2000) NOT NULL,
    IMAGE_URL VARCHAR2(500)
);

CREATE TABLE SURVEY_QUESTION (
    QUESTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_SURVEY_QUESTION PRIMARY KEY,

    QUESTION_TEXT VARCHAR2(500) NOT NULL,
    CATEGORY VARCHAR2(30) NOT NULL,
    DISPLAY_ORDER NUMBER NOT NULL
);

CREATE TABLE SURVEY_OPTION (
    OPTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_SURVEY_OPTION PRIMARY KEY,

    QUESTION_ID NUMBER NOT NULL,
    OPTION_TEXT VARCHAR2(300) NOT NULL,
    SCORE_CODE VARCHAR2(20) NOT NULL,
    SCORE_VALUE NUMBER DEFAULT 1 NOT NULL,
    IMAGE_URL VARCHAR2(500),

    CONSTRAINT FK_OPTION_QUESTION
        FOREIGN KEY (QUESTION_ID)
        REFERENCES SURVEY_QUESTION (QUESTION_ID)
        ON DELETE CASCADE,

    -- SurveyAnswer의 (QUESTION_ID, OPTION_ID) 복합 외래키가 참조할 수 있도록 유지
    CONSTRAINT UK_OPTION_QUESTION
        UNIQUE (QUESTION_ID, OPTION_ID)
);

CREATE TABLE TRAVEL_SURVEY (
    SURVEY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_TRAVEL_SURVEY PRIMARY KEY,

    MEMBER_ID NUMBER,
    GUEST_TOKEN VARCHAR2(100),
    REGION VARCHAR2(50) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,

    -- TravelSurvey 엔티티 필수 컬럼
    COMPANION_TYPE VARCHAR2(30) NOT NULL,
    TRANSPORT_TYPE VARCHAR2(30) NOT NULL,

    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    EXPIRES_AT DATE,
    CLAIMED_AT DATE,

    CONSTRAINT FK_SURVEY_MEMBER
        FOREIGN KEY (MEMBER_ID)
        REFERENCES MEMBER (MEMBER_ID)
        ON DELETE CASCADE,

    CONSTRAINT UK_SURVEY_GUEST_TOKEN
        UNIQUE (GUEST_TOKEN),

    CONSTRAINT CK_SURVEY_OWNER
        CHECK (MEMBER_ID IS NOT NULL OR GUEST_TOKEN IS NOT NULL),

    CONSTRAINT CK_SURVEY_DATE
        CHECK (END_DATE >= START_DATE),

    CONSTRAINT CK_SURVEY_CLAIMED_MEMBER
        CHECK (CLAIMED_AT IS NULL OR MEMBER_ID IS NOT NULL)
);

CREATE TABLE SURVEY_ANSWER (
    ANSWER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_SURVEY_ANSWER PRIMARY KEY,

    SURVEY_ID NUMBER NOT NULL,
    QUESTION_ID NUMBER NOT NULL,
    OPTION_ID NUMBER NOT NULL,

    CONSTRAINT FK_ANSWER_SURVEY
        FOREIGN KEY (SURVEY_ID)
        REFERENCES TRAVEL_SURVEY (SURVEY_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_ANSWER_QUESTION
        FOREIGN KEY (QUESTION_ID)
        REFERENCES SURVEY_QUESTION (QUESTION_ID),

    CONSTRAINT FK_ANSWER_OPTION
        FOREIGN KEY (QUESTION_ID, OPTION_ID)
        REFERENCES SURVEY_OPTION (QUESTION_ID, OPTION_ID),

    CONSTRAINT UK_ANSWER_SURVEY_QUESTION
        UNIQUE (SURVEY_ID, QUESTION_ID)
);

CREATE TABLE TRAVEL_TYPE_PLACE (
    TYPE_PLACE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_TRAVEL_TYPE_PLACE PRIMARY KEY,

    TRAVEL_CODE CHAR(5) NOT NULL,
    PLACE_ID NUMBER NOT NULL,
    WEIGHT_SCORE NUMBER DEFAULT 1 NOT NULL,

    CONSTRAINT FK_TYPE_PLACE_TYPE
        FOREIGN KEY (TRAVEL_CODE)
        REFERENCES TRAVEL_TYPE_MASTER (TRAVEL_CODE)
        ON DELETE CASCADE,

    CONSTRAINT FK_TYPE_PLACE_PLACE
        FOREIGN KEY (PLACE_ID)
        REFERENCES PLACES (PLACE_ID)
        ON DELETE CASCADE,

    CONSTRAINT UK_TYPE_PLACE
        UNIQUE (TRAVEL_CODE, PLACE_ID),

    CONSTRAINT CK_TYPE_PLACE_WEIGHT
        CHECK (WEIGHT_SCORE >= 0)
);

CREATE TABLE SURVEY_RESULT (
    RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_SURVEY_RESULT PRIMARY KEY,

    SURVEY_ID NUMBER NOT NULL,
    TRAVEL_CODE CHAR(5) NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT UK_RESULT_SURVEY
        UNIQUE (SURVEY_ID),

    CONSTRAINT FK_RESULT_SURVEY
        FOREIGN KEY (SURVEY_ID)
        REFERENCES TRAVEL_SURVEY (SURVEY_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_RESULT_TYPE
        FOREIGN KEY (TRAVEL_CODE)
        REFERENCES TRAVEL_TYPE_MASTER (TRAVEL_CODE)
);
