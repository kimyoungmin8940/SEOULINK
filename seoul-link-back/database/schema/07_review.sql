-- REVIEW_COMMENT
CREATE TABLE REVIEW_COMMENT (
    /* 후기 게시글 아래에 회원이 남기는 댓글과 논리 삭제 상태를 저장한다. */
    /* 댓글을 구분하는 자동 증가 기본키 */
    COMMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_REVIEW_COMMENT PRIMARY KEY,

    /* 댓글이 작성된 후기 번호(REVIEW 참조) */
    REVIEW_ID NUMBER NOT NULL,
    /* 댓글을 작성한 회원 번호(MEMBER 참조) */
    MEMBER_ID NUMBER NOT NULL,

    /* 사용자가 입력한 댓글 본문 */
    CONTENT VARCHAR2(500) NOT NULL,

    /* 댓글을 처음 작성한 일시 */
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    /* 댓글을 마지막으로 수정한 일시 */
    UPDATED_AT DATE,

    /* 실제 삭제 대신 숨김 처리 여부(Y/N) */
    IS_DELETED CHAR(1) DEFAULT 'N' NOT NULL,

    CONSTRAINT FK_COMMENT_REVIEW
        FOREIGN KEY (REVIEW_ID)
        REFERENCES REVIEW(REVIEW_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_COMMENT_MEMBER
        FOREIGN KEY (MEMBER_ID)
        REFERENCES MEMBER(MEMBER_ID),

    CONSTRAINT CK_COMMENT_DELETED
        CHECK (IS_DELETED IN ('Y', 'N'))
);
