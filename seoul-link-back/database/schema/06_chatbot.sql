-- 유료 챗봇의 질문·답변과 연결된 결제 및 여행 테마 이력을 저장합니다.
-- 같은 CONVERSATION_ID를 가진 행은 하나의 연속된 대화방으로 묶입니다.

CREATE TABLE CHATBOT_HISTORY (
    CHAT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_CHATBOT_HISTORY PRIMARY KEY,

    MEMBER_ID NUMBER NOT NULL,
    PAYMENT_ID NUMBER,
    CONVERSATION_ID VARCHAR2(36) NOT NULL,

    QUESTION CLOB NOT NULL,
    TRAVEL_CONCEPT VARCHAR2(100) NOT NULL,
    ANSWER CLOB NOT NULL,
    COURSE_SUMMARY CLOB,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT FK_CHATBOT_MEMBER
        FOREIGN KEY (MEMBER_ID) REFERENCES MEMBER(MEMBER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CHATBOT_PAYMENT
        FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT(PAYMENT_ID)
);

CREATE INDEX IDX_CHATBOT_HISTORY_MEMBER_CONVERSATION
    ON CHATBOT_HISTORY (MEMBER_ID, CONVERSATION_ID, CREATED_AT DESC);
