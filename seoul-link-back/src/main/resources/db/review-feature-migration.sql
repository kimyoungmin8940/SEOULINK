-- Existing database migration for the enhanced review feature.
-- Do NOT run the bootstrap SEOULINK.sql on a database containing data.

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE REVIEW ADD (COURSE_ID NUMBER, VISIT_DATE DATE, COMPANION VARCHAR2(30))';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE REVIEW ADD CONSTRAINT FK_REVIEW_COURSE FOREIGN KEY (COURSE_ID) REFERENCES TRAVEL_COURSES(COURSE_ID)';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -2264 AND SQLCODE != -2275 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE REVIEW_IMAGE (
        REVIEW_IMAGE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_REVIEW_IMAGE PRIMARY KEY,
        REVIEW_ID NUMBER NOT NULL, IMAGE_URL VARCHAR2(1000) NOT NULL, DISPLAY_ORDER NUMBER NOT NULL,
        CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT FK_REVIEW_IMAGE_REVIEW FOREIGN KEY (REVIEW_ID) REFERENCES REVIEW(REVIEW_ID) ON DELETE CASCADE,
        CONSTRAINT UK_REVIEW_IMAGE_ORDER UNIQUE (REVIEW_ID, DISPLAY_ORDER)
    )';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE REVIEW_TAG (
        REVIEW_TAG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_REVIEW_TAG PRIMARY KEY,
        REVIEW_ID NUMBER NOT NULL, TAG_NAME VARCHAR2(30) NOT NULL,
        CONSTRAINT FK_REVIEW_TAG_REVIEW FOREIGN KEY (REVIEW_ID) REFERENCES REVIEW(REVIEW_ID) ON DELETE CASCADE,
        CONSTRAINT UK_REVIEW_TAG UNIQUE (REVIEW_ID, TAG_NAME)
    )';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE ''ALTER TABLE REVIEW_IMAGE ADD CONSTRAINT CK_REVIEW_IMAGE_ORDER CHECK (DISPLAY_ORDER >= 1)'';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -2264 AND SQLCODE != -2261 THEN RAISE; END IF;
END;
/

-- 기존 REVIEW 테이블의 평점 제약을 0.0~5.0 범위로 교체한다.
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE REVIEW DROP CONSTRAINT CK_REVIEW_RATING';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -2443 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE REVIEW ADD CONSTRAINT CK_REVIEW_RATING CHECK (RATING BETWEEN 0.0 AND 5.0)';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -2264 THEN RAISE; END IF;
END;
/
